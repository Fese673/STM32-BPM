from pathlib import Path


def print_tree(path: Path, indent: int = 0, max_depth: int = 2):
    if indent > max_depth:
        return
    prefix = '    ' * indent
    if path.is_dir():
        print(f"{prefix}{path.name}/")
        if indent < max_depth:
            for child in sorted(path.iterdir(), key=lambda x: (not x.is_dir(), x.name.lower())):
                print_tree(child, indent + 1, max_depth)
    else:
        print(f"{prefix}{path.name}")


def print_section(title: str, path: Path, max_depth: int = 2):
    print(f"## {title}")
    print("```")
    print_tree(path, indent=0, max_depth=max_depth)
    print("```")
    print()


def main():
    root = Path(__file__).resolve().parent.parent

    print("# Project Map")
    print()
    print("Generated by `scripts/scan_project_map.py`. The output is organized by key directories and sample subtrees.")
    print()

    print_section('Root Directory', root, max_depth=1)

    for top in ['include', 'src', 'lib', 'test', 'EWARM', 'Drivers']:
        top_path = root / top
        if top_path.exists():
            print_section(f'{top} Directory', top_path, max_depth=2)


if __name__ == '__main__':
    main()
